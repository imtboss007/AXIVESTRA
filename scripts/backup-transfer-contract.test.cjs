"use strict";
const fs = require("node:fs");
const path = require("node:path");
const assert = require("node:assert/strict");
const root = path.resolve(__dirname, "..");
const read = file => fs.readFileSync(path.join(root, file), "utf8");
const app = read("src/App.tsx");
const main = read("electron/main.cjs");
const preload = read("electron/preload.cjs");
const env = read("src/vite-env.d.ts");
const pkg = JSON.parse(read("package.json"));
assert.match(app, /import \{ Directory, Encoding, Filesystem \} from "@capacitor\/filesystem"/);
assert.match(app, /import \{ Share \} from "@capacitor\/share"/);
assert.match(app, /Filesystem\.writeFile\([\s\S]{0,500}Directory\.Cache/);
assert.match(app, /Share\.share\([\s\S]{0,300}dialogTitle: "Save AXIVESTRA file"/);
assert.match(app, /window\.axivestraDesktop[\s\S]{0,300}saveFile/);
assert.match(app, /window\.axivestraDesktop[\s\S]{0,300}openTextFile/);
assert.match(app, /readBrowserFileText\(file\)/);
assert.match(app, /await localDb\.documents\.bulkPut\(restored\)/);
assert.match(app, /expectedSize !== bytes\.byteLength/);
assert.match(main, /ipcMain\.handle\("axivestra:save-file"/);
assert.match(main, /dialog\.showSaveDialog/);
assert.match(main, /ipcMain\.handle\("axivestra:open-text-file"/);
assert.match(main, /dialog\.showOpenDialog/);
assert.match(preload, /saveFile: payload => ipcRenderer\.invoke\("axivestra:save-file"/);
assert.match(preload, /openTextFile: \(\) => ipcRenderer\.invoke\("axivestra:open-text-file"/);
assert.match(env, /axivestraDesktop\?:/);
assert.equal(pkg.dependencies["@capacitor/filesystem"], "^6.0.4");
assert.equal(pkg.dependencies["@capacitor/share"], "^6.0.4");
console.log("AXIVESTRA cross-platform backup transfer contracts passed.");
